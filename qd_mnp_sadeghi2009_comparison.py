"""Native-model comparison with Sadeghi, Nanotechnology 20, 225401 (2009).

Sadeghi considers one spherical metallic nanoparticle (MNP) and one
two-level quantum dot (QD), aligned with the incident polarization.  This is
the spherical, longitudinal ``G=2`` limit of ``qd_mnp_rational_fit.py``.

The article works in the rotating-wave approximation (RWA), eliminates the
MNP adiabatically and follows nanosecond dynamics.  Calling the native
carrier-resolved solver for several nanoseconds would resolve millions of
optical periods.  The adapter below therefore evaluates the *same passive
modal polarizability* at the laser carrier and integrates the resulting RWA
density-matrix equations.  The mathematical core is not modified.

For the paper-convention coherence ``s=rho_21`` used here, define
``Omega=-Omega_paper`` so that the printed negative bare coupling becomes a
positive drive magnitude.  The equations are

    Omega = Omega0(t) * (1 + J*alpha) + eta*s,
    eta   = d**2 * l_QD**2 * J**2 * alpha,
    dot p = 2 Im(Omega.conj()*s) - gamma1*p,
    dot s = -(Gamma2 + i*Delta)*s + i*Omega*(1 - 2*p),

where ``p=rho_22``, ``J=2/(eps_h*R**3)`` and ``alpha`` is the physical MNP
polarizability from the project.  These equations are the adiabatic RWA limit
of the native Bloch/modal equations: the plasmon coordinates have been
eliminated after evaluating their passive modal response at the carrier.

The PDF does not state the numerical MNP radius, host/QD permittivities,
transition energy or metal data.  The commonly used values below are
reconstructed from the model cited as reference 9 by Sadeghi.  They are kept
separate from constants printed directly in the article.  The project also
uses Johnson--Christy Au data, whereas the cited source used Palik; exact
pixel-level reproduction is therefore neither claimed nor expected.
"""

