def _sphere_material_alpha_dimless(
    params: HybridSystemParams,
    energies_ev: float | np.ndarray,
) -> np.ndarray:
    epsilon_gold = params.material.epsilon_at(energies_ev)
    contrast = epsilon_gold - params.eps_m
    return np.asarray(
        contrast / (params.eps_m + contrast / 3.0),
        dtype=complex,
    )


def _modal_alpha_dimless(
    fit: RationalLorentzFit,
    energies_ev: float | np.ndarray,
) -> np.ndarray:
    omega = np.asarray(eV_to_au(energies_ev), dtype=float)
    alpha = np.full_like(omega, fit.alpha_inf, dtype=complex)
    for strength, mode_omega, mode_gamma in zip(
        fit.strengths_au2,
        fit.omega_modes_au,
        fit.gamma_modes_au,
    ):
        alpha += strength / (
            mode_omega**2 - omega**2 - 1j * mode_gamma * omega
        )
    return alpha


def _cached_sadeghi_fit(params: HybridSystemParams) -> RationalLorentzFit:
    mask = (
        (params.material.energy_eV >= 0.8)
        & (params.material.energy_eV <= 3.0)
    )
    dense_energies = np.linspace(0.8, 3.0, max(1025, 256 * 9))
    energies = np.unique(
        np.concatenate(
            ([0.8, 3.0], dense_energies, params.material.energy_eV[mask])
        )
    )
    target = _sphere_material_alpha_dimless(params, energies)
    omega = np.asarray(eV_to_au(energies), dtype=float)
    fitted = np.full_like(omega, _SADEGHI_N9_ALPHA_INF, dtype=complex)
    for strength, mode_energy, mode_gamma in zip(
        _SADEGHI_N9_STRENGTHS_AU2,
        _SADEGHI_N9_OMEGA_EV,
        _SADEGHI_N9_GAMMA_EV,
    ):
        mode_omega_au = float(eV_to_au(mode_energy))
        mode_gamma_au = float(eV_to_au(mode_gamma))
        fitted += strength / (
            mode_omega_au**2 - omega**2 - 1j * mode_gamma_au * omega
        )
    inverse_target = 1.0 / target
    inverse_fitted = 1.0 / fitted
    alpha_error = fitted - target
    inverse_error = inverse_fitted - inverse_target
    rms_alpha = float(np.sqrt(np.mean(np.abs(alpha_error) ** 2)))
    rms_inverse = float(np.sqrt(np.mean(np.abs(inverse_error) ** 2)))
    normalized_rms_alpha = rms_alpha / float(
        np.sqrt(np.mean(np.abs(target) ** 2))
    )
    normalized_rms_inverse = rms_inverse / float(
        np.sqrt(np.mean(np.abs(inverse_target) ** 2))
    )
    max_normalized_error = float(np.max(np.abs(alpha_error) / np.abs(target)))
    residual_parts = [
        alpha_error.real / max(float(np.max(np.abs(target.real))), 1.0e-12),
        alpha_error.imag / max(float(np.max(np.abs(target.imag))), 1.0e-12),
        np.sqrt(1.2)
        * inverse_error.real
        / max(float(np.max(np.abs(inverse_target.real))), 1.0e-12),
        np.sqrt(1.2)
        * inverse_error.imag
        / max(float(np.max(np.abs(inverse_target.imag))), 1.0e-12),
    ]
    cached_score = float(np.sqrt(np.mean(np.concatenate(residual_parts) ** 2)))
    passivity_energies = np.linspace(0.8, 3.0, max(1024, 256 * 9))
    passivity_omega = np.asarray(eV_to_au(passivity_energies), dtype=float)
    passivity_alpha = np.full_like(
        passivity_omega,
        _SADEGHI_N9_ALPHA_INF,
        dtype=complex,
    )
    for strength, mode_energy, mode_gamma in zip(
        _SADEGHI_N9_STRENGTHS_AU2,
        _SADEGHI_N9_OMEGA_EV,
        _SADEGHI_N9_GAMMA_EV,
    ):
        mode_omega_au = float(eV_to_au(mode_energy))
        mode_gamma_au = float(eV_to_au(mode_gamma))
        passivity_alpha += strength / (
            mode_omega_au**2
            - passivity_omega**2
            - 1j * mode_gamma_au * passivity_omega
        )
    minimum_imaginary = float(np.min(passivity_alpha.imag))
    return RationalLorentzFit(
        alpha_inf=_SADEGHI_N9_ALPHA_INF,
        strengths_au2=_SADEGHI_N9_STRENGTHS_AU2,
        omega_modes_au=np.asarray(eV_to_au(_SADEGHI_N9_OMEGA_EV), dtype=float),
        gamma_modes_au=np.asarray(eV_to_au(_SADEGHI_N9_GAMMA_EV), dtype=float),
        energies_used_eV=energies,
        alpha_used=target,
        rms_alpha=rms_alpha,
        rms_inv_alpha=rms_inverse,
        cost=cached_score,
        normalized_rms_alpha=normalized_rms_alpha,
        normalized_rms_inv_alpha=normalized_rms_inverse,
        max_normalized_alpha_error=max_normalized_error,
        min_imag_alpha_fit_window=minimum_imaginary,
        passivity_grid_points=int(passivity_omega.size),
        passive_on_fit_window=True,
        passive_for_all_positive_frequencies=True,
    )


@dataclass(frozen=True)
class SadeghiCoupling:
    laser_energy_ev: float
    distance_nm: float
    alpha_mnp_au: complex
    direct_factor: complex
    feedback_ns_inv: complex
    point_qd_surface_gap_nm: float


class SadeghiRWAAdapter:
    """Adiabatic spherical ``G=2`` RWA limit of the unchanged native model."""

    fit_window_ev = (0.8, 3.0)

    def __init__(
        self,
        profile: Sadeghi2009Profile | None = None,
        *,
        fit: RationalLorentzFit | None = None,
    ) -> None:
        self.profile = profile or Sadeghi2009Profile()
        self.params = build_sadeghi_params(self.profile)
        self.fit = fit or _cached_sadeghi_fit(self.params)
        self.C = (
            self.params.eps_m
            * self.params.a_au**2
            * self.params.c_au
            / 3.0
        )

    def alpha_dimless(
        self,
        energies_ev: float | np.ndarray,
        *,
        response: MNPResponse = "modal",
    ) -> np.ndarray:
        energies = np.asarray(energies_ev, dtype=float)
        if np.any(~np.isfinite(energies)):
            raise ValueError("Requested energies must be finite.")
        if response == "modal":
            lo, hi = self.fit_window_ev
            if np.any(energies < lo) or np.any(energies > hi):
                raise ValueError("Modal response requested outside the 0.8--3.0 eV fit window.")
            return _modal_alpha_dimless(self.fit, energies)
        if response == "material":
            return _sphere_material_alpha_dimless(self.params, energies)
        raise ValueError("response must be 'modal' or 'material'.")

    def alpha_physical_au(
        self,
        energies_ev: float | np.ndarray,
        *,
        response: MNPResponse = "modal",
    ) -> np.ndarray:
        return self.C * self.alpha_dimless(energies_ev, response=response)

    def coupling(
        self,
        *,
        laser_energy_ev: float,
        distance_nm: float,
        response: MNPResponse = "modal",
    ) -> SadeghiCoupling:
        gap = self.profile.surface_gap_nm(distance_nm)
        if gap <= 0.0:
            raise ValueError("The point-QD surface gap must be strictly positive.")
        distance_au = float(nm_to_au(distance_nm))
        alpha = complex(self.alpha_physical_au(laser_energy_ev, response=response))
        J = 2.0 / (self.params.eps_m * distance_au**3)
        local = self.params.qd_local_field_factor
        eta_au = self.params.d_au**2 * local**2 * J**2 * alpha
        return SadeghiCoupling(
            laser_energy_ev=float(laser_energy_ev),
            distance_nm=float(distance_nm),
            alpha_mnp_au=alpha,
            direct_factor=complex(1.0 + J * alpha),
            feedback_ns_inv=complex(_rate_au_to_ns_inv(eta_au)),
            point_qd_surface_gap_nm=gap,
        )


def build_sadeghi_adapter(
    profile: Sadeghi2009Profile | None = None,
    *,
    refit: bool = False,
) -> SadeghiRWAAdapter:
    profile = profile or Sadeghi2009Profile()
    if not refit:
        return SadeghiRWAAdapter(profile)
    params = build_sadeghi_params(profile)
    core_model = HybridQDPlasmonModel(
        params,
        orientation="long",
        n_modes=9,
        fit_window_eV=(0.8, 3.0),
        radiative_consistency_policy="ignore",
        verbose=True,
    )
    return SadeghiRWAAdapter(profile, fit=core_model.fit)


@dataclass(frozen=True)
class SadeghiSteadyState:
    detuning_mev: float
    laser_energy_ev: float
    distance_nm: float
    intensity_w_cm2: float
    excited_population: float
    coherence_21: complex
    normalized_rabi_ns_inv: complex
    physical_excitation_ns_inv: float
    literal_paper_G_ns_inv: float
    negated_physical_excitation_ns_inv: float
    bloch_radius: float
    residual_norm: float
    max_jacobian_real_part_ns_inv: float
    locally_stable: bool
    solver_success: bool


def isolated_steady_state(
    *,
    omega_ns_inv: complex,
    detuning_ns_inv: float,
    gamma1_ns_inv: float,
    gamma2_ns_inv: float,
) -> tuple[float, complex]:
    """Analytic stationary state for an isolated coherently driven TLS."""

    denominator = gamma2_ns_inv**2 + detuning_ns_inv**2
    pumping = 2.0 * abs(omega_ns_inv) ** 2 * gamma2_ns_inv / denominator
    population = pumping / (gamma1_ns_inv + 2.0 * pumping)
    inversion_ground_minus_excited = 1.0 - 2.0 * population
    coherence = (
        1j
        * omega_ns_inv
        * inversion_ground_minus_excited
        / (gamma2_ns_inv + 1j * detuning_ns_inv)
    )
    return float(population), complex(coherence)


def _steady_residual(
    vector: np.ndarray,
    *,
    omega0_ns_inv: float,
    coupling: SadeghiCoupling,
    detuning_ns_inv: float,
    gamma1_ns_inv: float,
    gamma2_ns_inv: float,
) -> np.ndarray:
    population, coherence_real, coherence_imag = vector
    coherence = complex(coherence_real, coherence_imag)
    omega = omega0_ns_inv * coupling.direct_factor + coupling.feedback_ns_inv * coherence
    population_dot = (
        2.0 * np.imag(np.conj(omega) * coherence)
        - gamma1_ns_inv * population
    )
    coherence_dot = (
        -(gamma2_ns_inv + 1j * detuning_ns_inv) * coherence
        + 1j * omega * (1.0 - 2.0 * population)
    )
    scale = max(
        gamma1_ns_inv,
        gamma2_ns_inv,
        abs(detuning_ns_inv),
        abs(omega0_ns_inv),
        abs(coupling.feedback_ns_inv),
        1.0,
    )
    return np.asarray(
        [population_dot, coherence_dot.real, coherence_dot.imag],
        dtype=float,
    ) / scale


def steady_state_jacobian_ns_inv(
    *,
    population: float,
    coherence_21: complex,
    direct_drive_ns_inv: complex,
    feedback_ns_inv: complex,
    detuning_ns_inv: float,
    gamma1_ns_inv: float,
    gamma2_ns_inv: float,
) -> np.ndarray:
    """Jacobian of the physical RWA equations in ``(rho22, Re s, Im s)``."""

    x = float(coherence_21.real)
    y = float(coherence_21.imag)
    direct_real = float(direct_drive_ns_inv.real)
    direct_imag = float(direct_drive_ns_inv.imag)
    feedback_real = float(feedback_ns_inv.real)
    feedback_imag = float(feedback_ns_inv.imag)
    inversion = 1.0 - 2.0 * population
    omega_real = direct_real + feedback_real * x - feedback_imag * y
    omega_imag = direct_imag + feedback_imag * x + feedback_real * y
    return np.asarray(
        [
            [
                -gamma1_ns_inv,
                -2.0 * direct_imag - 4.0 * feedback_imag * x,
                2.0 * direct_real - 4.0 * feedback_imag * y,
            ],
            [
                2.0 * omega_imag,
                -gamma2_ns_inv - feedback_imag * inversion,
                detuning_ns_inv - feedback_real * inversion,
            ],
            [
                -2.0 * omega_real,
                -detuning_ns_inv + feedback_real * inversion,
                -gamma2_ns_inv - feedback_imag * inversion,
            ],
        ],
        dtype=float,
    )


def solve_steady_state(
    adapter: SadeghiRWAAdapter,
    *,
    detuning_mev: float,
    distance_nm: float,
    intensity_w_cm2: float,
    response: MNPResponse = "modal",
    initial_state: SadeghiSteadyState | None = None,
) -> SadeghiSteadyState:
    """Solve one converged, positive article-style RWA fixed point."""

    profile = adapter.profile
    laser_energy_ev = profile.transition_energy_ev - detuning_mev * 1.0e-3
    coupling = adapter.coupling(
        laser_energy_ev=laser_energy_ev,
        distance_nm=distance_nm,
        response=response,
    )
    detuning_ns_inv = detuning_mev * MEV_TO_NS_INV
    omega0 = profile.isolated_rabi_ns_inv(intensity_w_cm2)
    if initial_state is None:
        initial_population, initial_coherence = isolated_steady_state(
            omega_ns_inv=omega0 * coupling.direct_factor,
            detuning_ns_inv=detuning_ns_inv,
            gamma1_ns_inv=profile.population_decay_ns_inv,
            gamma2_ns_inv=profile.coherence_decay_ns_inv,
        )
        initial = np.asarray(
            [initial_population, initial_coherence.real, initial_coherence.imag],
            dtype=float,
        )
    else:
        initial = np.asarray(
            [
                initial_state.excited_population,
                initial_state.coherence_21.real,
                initial_state.coherence_21.imag,
            ],
            dtype=float,
        )

    result = least_squares(
        _steady_residual,
        initial,
        bounds=(np.asarray([0.0, -0.5, -0.5]), np.asarray([0.5, 0.5, 0.5])),
        args=(),
        kwargs={
            "omega0_ns_inv": omega0,
            "coupling": coupling,
            "detuning_ns_inv": detuning_ns_inv,
            "gamma1_ns_inv": profile.population_decay_ns_inv,
            "gamma2_ns_inv": profile.coherence_decay_ns_inv,
        },
        xtol=1.0e-13,
        ftol=1.0e-13,
        gtol=1.0e-13,
        max_nfev=3000,
    )
    solution_vector = np.asarray(result.x, dtype=float)
    bounded_residual = float(
        np.linalg.norm(
            _steady_residual(
                solution_vector,
                omega0_ns_inv=omega0,
                coupling=coupling,
                detuning_ns_inv=detuning_ns_inv,
                gamma1_ns_inv=profile.population_decay_ns_inv,
                gamma2_ns_inv=profile.coherence_decay_ns_inv,
            )
        )
    )
    # On the far-detuned tails rho22 can be so close to the lower bound that
    # the bounded optimizer terminates by projected-gradient tolerance before
    # driving all equations to machine precision.  One local Newton polishing
    # step removes that harmless active-bound residual; the physical domain is
    # checked again below.
    if bounded_residual > 1.0e-10:
        polished = root(
            lambda vector: _steady_residual(
                vector,
                omega0_ns_inv=omega0,
                coupling=coupling,
                detuning_ns_inv=detuning_ns_inv,
                gamma1_ns_inv=profile.population_decay_ns_inv,
                gamma2_ns_inv=profile.coherence_decay_ns_inv,
            ),
            solution_vector,
            method="hybr",
            options={"xtol": 1.0e-11, "maxfev": 2000},
        )
        polished_residual = float(
            np.linalg.norm(
                _steady_residual(
                    polished.x,
                    omega0_ns_inv=omega0,
                    coupling=coupling,
                    detuning_ns_inv=detuning_ns_inv,
                    gamma1_ns_inv=profile.population_decay_ns_inv,
                    gamma2_ns_inv=profile.coherence_decay_ns_inv,
                )
            )
        )
        if polished_residual < bounded_residual:
            solution_vector = np.asarray(polished.x, dtype=float)

    population = float(solution_vector[0])
    coherence = complex(solution_vector[1], solution_vector[2])
    omega = omega0 * coupling.direct_factor + coupling.feedback_ns_inv * coherence
    excitation = float(2.0 * np.imag(np.conj(omega) * coherence))
    bloch_radius = float(
        np.sqrt((1.0 - 2.0 * population) ** 2 + 4.0 * abs(coherence) ** 2)
    )
    residual_norm = float(
        np.linalg.norm(
            _steady_residual(
                solution_vector,
                omega0_ns_inv=omega0,
                coupling=coupling,
                detuning_ns_inv=detuning_ns_inv,
                gamma1_ns_inv=profile.population_decay_ns_inv,
                gamma2_ns_inv=profile.coherence_decay_ns_inv,
            )
        )
    )
    # The residual is already divided by the largest optical/RWA rate.  A
    # 1e-8 dimensionless gate is far below the accuracy visible in any saved
    # observable, while avoiding false failures when a bounded solution sits
    # close to rho22=0 on the far-detuned tails.
    success = bool(residual_norm <= 1.0e-8)
    if not success:
        raise RuntimeError(
            "Sadeghi steady-state solve did not converge: "
            f"message={result.message!s}, residual={residual_norm:.6g}."
        )
    if population < -2.0e-10 or population > 0.5 + 2.0e-8:
        raise RuntimeError(
            "The stationary population lies outside the passive CW interval: "
            f"rho22={population:.9g}."
        )
    population = float(np.clip(population, 0.0, 0.5))
    if bloch_radius > 1.0 + 2.0e-7:
        raise RuntimeError(
            "The stationary density matrix is not positive: "
            f"Bloch radius={bloch_radius:.9g}."
        )
    jacobian = steady_state_jacobian_ns_inv(
        population=population,
        coherence_21=coherence,
        direct_drive_ns_inv=omega0 * coupling.direct_factor,
        feedback_ns_inv=coupling.feedback_ns_inv,
        detuning_ns_inv=detuning_ns_inv,
        gamma1_ns_inv=profile.population_decay_ns_inv,
        gamma2_ns_inv=profile.coherence_decay_ns_inv,
    )
    maximum_jacobian_real_part = float(
        np.max(np.linalg.eigvals(jacobian).real)
    )
    locally_stable = bool(maximum_jacobian_real_part < 0.0)
    if not locally_stable:
        raise RuntimeError(
            "The converged Sadeghi fixed point is locally unstable: "
            f"max Re(lambda)={maximum_jacobian_real_part:.9g} ns^-1."
        )
    return SadeghiSteadyState(
        detuning_mev=float(detuning_mev),
        laser_energy_ev=float(laser_energy_ev),
        distance_nm=float(distance_nm),
        intensity_w_cm2=float(intensity_w_cm2),
        excited_population=population,
        coherence_21=coherence,
        normalized_rabi_ns_inv=complex(omega),
        physical_excitation_ns_inv=excitation,
        # With Omega_script=-Omega_paper, the expression printed by Sadeghi is
        # 2 Im(Omega_paper*rho21) = -2 Im(Omega_script*rho21).  For a complex
        # Omega this is not identically the negative of the Hermitian physical
        # pumping term 2 Im(conj(Omega_script)*rho21), so both are retained.
        literal_paper_G_ns_inv=float(-2.0 * np.imag(omega * coherence)),
        negated_physical_excitation_ns_inv=-excitation,
        bloch_radius=bloch_radius,
        residual_norm=residual_norm,
        max_jacobian_real_part_ns_inv=maximum_jacobian_real_part,
        locally_stable=locally_stable,
        solver_success=success,
    )


def solve_steady_sweep(
    adapter: SadeghiRWAAdapter,
    detunings_mev: Iterable[float],
    *,
    distance_nm: float,
    intensity_w_cm2: float,
    response: MNPResponse = "modal",
) -> list[SadeghiSteadyState]:
    states: list[SadeghiSteadyState] = []
    previous: SadeghiSteadyState | None = None
    for detuning in np.asarray(tuple(detunings_mev), dtype=float):
        state = solve_steady_state(
            adapter,
            detuning_mev=float(detuning),
            distance_nm=distance_nm,
            intensity_w_cm2=intensity_w_cm2,
            response=response,
            initial_state=previous,
        )
        states.append(state)
        previous = state
    return states


def validate_detuning_grid_resolution(
    detunings_mev: Iterable[float],
    profile: Sadeghi2009Profile,
    *,
    max_step_fraction_of_gamma2: float = MAX_DETUNING_STEP_FRACTION_OF_GAMMA2,
) -> float:
    """Reject a publication grid that cannot resolve the bare QD linewidth.

    Strong driving can power-broaden a particular curve, but the same sweep
    also contains the weakly coupled/far-distance limit.  We therefore keep
    the conservative project-wide criterion ``dE <= hbar*Gamma2/4`` instead
    of silently relying on power broadening.
    """

    detunings = np.asarray(tuple(detunings_mev), dtype=float)
    if detunings.ndim != 1 or detunings.size < 2:
        raise ValueError("A detuning grid needs at least two points.")
    if np.any(~np.isfinite(detunings)) or np.any(np.diff(detunings) <= 0.0):
        raise ValueError("The detuning grid must be finite and strictly increasing.")
    if (
        not np.isfinite(max_step_fraction_of_gamma2)
        or max_step_fraction_of_gamma2 <= 0.0
    ):
        raise ValueError("max_step_fraction_of_gamma2 must be finite and positive.")
    maximum_step = float(np.max(np.diff(detunings)))
    gamma2_mev = profile.coherence_decay_ns_inv / MEV_TO_NS_INV
    allowed_step = max_step_fraction_of_gamma2 * gamma2_mev
    tolerance = 1.0e-12 * max(allowed_step, 1.0e-12)
    if maximum_step > allowed_step + tolerance:
        raise ValueError(
            "The Sadeghi detuning grid under-resolves the QD coherence width: "
            f"max step={maximum_step:.6g} meV, allowed<={allowed_step:.6g} meV "
            f"(Gamma2={gamma2_mev:.6g} meV). Increase the number of points."
        )
    return maximum_step


def logistic_switch_envelope(
    time_ns: float | np.ndarray,
    *,
    center_ns: float,
    rise_10_90_ns: float,
) -> np.ndarray:
    """Amplitude ramp whose 10--90 percent interval is exactly specified."""

    if rise_10_90_ns <= 0.0:
        raise ValueError("rise_10_90_ns must be positive.")
    slope = 2.0 * np.log(9.0) / rise_10_90_ns
    argument = np.clip(slope * (np.asarray(time_ns) - center_ns), -700.0, 700.0)
    return 1.0 / (1.0 + np.exp(-argument))


@dataclass(frozen=True)
class SadeghiTimeTrace:
    time_ns: np.ndarray
    distance_nm: float
    detuning_mev: float
    intensity_w_cm2: float
    excited_population: np.ndarray
    coherence_21: np.ndarray
    normalized_rabi_ns_inv: np.ndarray
    physical_excitation_ns_inv: np.ndarray
    literal_paper_G_ns_inv: np.ndarray
    negated_physical_excitation_ns_inv: np.ndarray
    drive_envelope: np.ndarray
    max_bloch_radius: float
    min_density_eigenvalue: float
    solver_success: bool
    nfev: int


def solve_switch_on_trace(
    adapter: SadeghiRWAAdapter,
    *,
    distance_nm: float,
    detuning_mev: float,
    intensity_w_cm2: float | None = None,
    response: MNPResponse = "modal",
    points: int = 2251,
    rtol: float = 2.0e-9,
    atol: float = 2.0e-11,
) -> SadeghiTimeTrace:
    """Integrate the physical RWA density matrix during the assumed ramp."""

    if points < 3:
        raise ValueError("points must be at least 3.")
    profile = adapter.profile
    intensity = (
        profile.strong_intensity_w_cm2
        if intensity_w_cm2 is None
        else float(intensity_w_cm2)
    )
    laser_energy_ev = profile.transition_energy_ev - detuning_mev * 1.0e-3
    coupling = adapter.coupling(
        laser_energy_ev=laser_energy_ev,
        distance_nm=distance_nm,
        response=response,
    )
    omega0_max = profile.isolated_rabi_ns_inv(intensity)
    detuning_ns_inv = detuning_mev * MEV_TO_NS_INV

    def rhs(time_ns: float, vector: np.ndarray) -> np.ndarray:
        population, coherence_real, coherence_imag = vector
        coherence = complex(coherence_real, coherence_imag)
        envelope = float(
            logistic_switch_envelope(
                time_ns,
                center_ns=profile.switch_center_ns,
                rise_10_90_ns=profile.switch_rise_10_90_ns,
            )
        )
        omega = (
            omega0_max * envelope * coupling.direct_factor
            + coupling.feedback_ns_inv * coherence
        )
        population_dot = (
            2.0 * np.imag(np.conj(omega) * coherence)
            - profile.population_decay_ns_inv * population
        )
        coherence_dot = (
            -(profile.coherence_decay_ns_inv + 1j * detuning_ns_inv)
            * coherence
            + 1j * omega * (1.0 - 2.0 * population)
        )
        return np.asarray(
            [population_dot, coherence_dot.real, coherence_dot.imag],
            dtype=float,
        )

    times = np.linspace(profile.time_start_ns, profile.time_end_ns, points)
    maximum_rate = max(
        abs(detuning_ns_inv),
        omega0_max * abs(coupling.direct_factor),
        abs(coupling.feedback_ns_inv),
        profile.coherence_decay_ns_inv,
        1.0,
    )
    max_step = min(0.005, 0.12 / maximum_rate)
    solution = solve_ivp(
        rhs,
        (profile.time_start_ns, profile.time_end_ns),
        np.asarray([0.0, 0.0, 0.0]),
        t_eval=times,
        method="DOP853",
        rtol=rtol,
        atol=atol,
        max_step=max_step,
    )
    if not solution.success or solution.t.size != times.size:
        raise RuntimeError(f"Sadeghi time integration failed: {solution.message}")
    population = np.asarray(solution.y[0], dtype=float)
    coherence = np.asarray(solution.y[1] + 1j * solution.y[2], dtype=complex)
    envelope = logistic_switch_envelope(
        times,
        center_ns=profile.switch_center_ns,
        rise_10_90_ns=profile.switch_rise_10_90_ns,
    )
    omega = (
        omega0_max * envelope * coupling.direct_factor
        + coupling.feedback_ns_inv * coherence
    )
    excitation = 2.0 * np.imag(np.conj(omega) * coherence)
    bloch_radius = np.sqrt(
        (1.0 - 2.0 * population) ** 2 + 4.0 * np.abs(coherence) ** 2
    )
    minimum_eigenvalue = 0.5 * (1.0 - bloch_radius)
    if np.max(bloch_radius) > 1.0 + 2.0e-6:
        raise RuntimeError(
            "The time-dependent density matrix lost positivity: "
            f"max Bloch radius={np.max(bloch_radius):.9g}."
        )
    return SadeghiTimeTrace(
        time_ns=times,
        distance_nm=float(distance_nm),
        detuning_mev=float(detuning_mev),
        intensity_w_cm2=intensity,
        excited_population=population,
        coherence_21=coherence,
        normalized_rabi_ns_inv=np.asarray(omega, dtype=complex),
        physical_excitation_ns_inv=np.asarray(excitation, dtype=float),
        literal_paper_G_ns_inv=np.asarray(
            -2.0 * np.imag(omega * coherence),
            dtype=float,
        ),
        negated_physical_excitation_ns_inv=np.asarray(-excitation, dtype=float),
        drive_envelope=np.asarray(envelope, dtype=float),
        max_bloch_radius=float(np.max(bloch_radius)),
        min_density_eigenvalue=float(np.min(minimum_eigenvalue)),
        solver_success=True,
        nfev=int(solution.nfev),
    )


def _write_csv(path: Path, fieldnames: list[str], rows: Iterable[dict[str, object]]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(rows)


def _pdf_sha256(path: Path) -> str | None:
    if not path.exists():
        return None
    return hashlib.sha256(path.read_bytes()).hexdigest()


def _default_run_dir() -> Path:
    stamp = datetime.now().strftime("%Y%m%d_%H%M%S")
    return Path("results") / "sadeghi2009_comparison" / stamp


