@dataclass(frozen=True)
class Sadeghi2009Profile:
    """Article constants plus an explicitly identified reconstructed profile."""

    # Printed directly in Sadeghi 2009.
    transition_dipole_e_nm: float = 0.65
    population_lifetime_ns: float = 0.8
    coherence_decay_ns_inv: float = 2.7
    weak_intensity_w_cm2: float = 1.0
    strong_intensity_w_cm2: float = 1.0e3
    distances_nm: tuple[float, ...] = (100.0, 20.0, 17.0, 15.0)

    # Reconstructed from the Zhang--Govorov--Bryant model cited by Sadeghi.
    sphere_radius_nm: float = 7.5
    eps_environment: float = 1.0
    eps_qd: float = 6.0
    transition_energy_ev: float = 2.5
    qd_radius_nm: float = 0.0

    # The exact ramp is not printed; this is an explicit project assumption.
    switch_center_ns: float = 10.0
    switch_rise_10_90_ns: float = 0.4
    time_start_ns: float = 8.5
    time_end_ns: float = 13.0

    def __post_init__(self) -> None:
        values = np.asarray(
            [
                self.transition_dipole_e_nm,
                self.population_lifetime_ns,
                self.coherence_decay_ns_inv,
                self.weak_intensity_w_cm2,
                self.strong_intensity_w_cm2,
                self.sphere_radius_nm,
                self.eps_environment,
                self.eps_qd,
                self.transition_energy_ev,
                self.switch_rise_10_90_ns,
            ],
            dtype=float,
        )
        if np.any(~np.isfinite(values)) or np.any(values <= 0.0):
            raise ValueError("All positive Sadeghi profile constants must be finite.")
        if not np.isfinite(self.qd_radius_nm) or self.qd_radius_nm < 0.0:
            raise ValueError("qd_radius_nm must be finite and non-negative.")
        if self.time_end_ns <= self.time_start_ns:
            raise ValueError("time_end_ns must be greater than time_start_ns.")
        if len(self.distances_nm) == 0 or any(
            not np.isfinite(value) or value <= 0.0
            for value in self.distances_nm
        ):
            raise ValueError("distances_nm must contain positive finite values.")
        if min(self.surface_gap_nm(value) for value in self.distances_nm) <= 0.0:
            raise ValueError("Every Sadeghi geometry must have a positive surface gap.")
        if self.coherence_decay_ns_inv < 0.5 * self.population_decay_ns_inv:
            raise ValueError("The profile must satisfy Gamma2 >= gamma1/2.")

    @property
    def population_decay_ns_inv(self) -> float:
        return 1.0 / self.population_lifetime_ns

    @property
    def pure_dephasing_ns_inv(self) -> float:
        return self.coherence_decay_ns_inv - 0.5 * self.population_decay_ns_inv

    @property
    def transition_dipole_debye(self) -> float:
        return _dipole_enm_to_debye(self.transition_dipole_e_nm)

    @property
    def qd_local_field_factor(self) -> float:
        return 3.0 * self.eps_environment / (
            self.eps_qd + 2.0 * self.eps_environment
        )

    @property
    def epsilon_eff1(self) -> float:
        return 1.0 / self.qd_local_field_factor

    def surface_gap_nm(self, distance_nm: float) -> float:
        return float(distance_nm - self.sphere_radius_nm - self.qd_radius_nm)

    def field_amplitude_v_m(self, intensity_w_cm2: float) -> float:
        """Return the real-field peak using the project's host normalization."""

        if not np.isfinite(intensity_w_cm2) or intensity_w_cm2 < 0.0:
            raise ValueError("intensity_w_cm2 must be finite and non-negative.")
        refractive_index = np.sqrt(self.eps_environment)
        return float(
            np.sqrt(
                2.0
                * intensity_w_cm2
                * 1.0e4
                / (refractive_index * epsilon_0 * C_SI)
            )
        )

    def isolated_rabi_ns_inv(self, intensity_w_cm2: float) -> float:
        """Article's half-Rabi coupling |mu E0|/(2 hbar eps_eff1)."""

        dipole_si = self.transition_dipole_e_nm * E_CHARGE * 1.0e-9
        omega_s_inv = (
            dipole_si
            * self.qd_local_field_factor
            * self.field_amplitude_v_m(intensity_w_cm2)
            / (2.0 * hbar)
        )
        return float(omega_s_inv * 1.0e-9)

    def provenance(self) -> dict[str, object]:
        return {
            "direct_from_sadeghi2009": {
                "transition_dipole_e_nm": self.transition_dipole_e_nm,
                "population_lifetime_ns": self.population_lifetime_ns,
                "coherence_decay_ns_inv": self.coherence_decay_ns_inv,
                "weak_intensity_w_cm2": self.weak_intensity_w_cm2,
                "strong_intensity_w_cm2": self.strong_intensity_w_cm2,
                "distances_nm": list(self.distances_nm),
            },
            "inferred_from_sadeghi_reference_9": {
                "sphere_radius_nm": self.sphere_radius_nm,
                "eps_environment": self.eps_environment,
                "eps_qd": self.eps_qd,
                "transition_energy_ev": self.transition_energy_ev,
            },
            "project_model_choices": {
                "gold_data": "Johnson-Christy table bundled with the project",
                "paper_reference_gold_data": "Palik",
                "qd_radius_nm": self.qd_radius_nm,
                "qd_geometry_reason": (
                    "point-QD because neither Sadeghi nor its reference-9 "
                    "parameter list specifies a QD radius for this calculation"
                ),
                "switch_on": (
                    "logistic amplitude ramp with the stated 10--90 percent "
                    "rise time; exact article ramp is unavailable"
                ),
                "ground_state_decay_gamma11": 0.0,
            },
        }


