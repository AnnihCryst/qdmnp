def _build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description=(
            "Calculate Sadeghi-2009 figure analogues with the unchanged native "
            "quasistatic QD-MNP model."
        )
    )
    parser.add_argument("--output-dir", type=Path)
    parser.add_argument("--response", choices=("modal", "material"), default="modal")
    parser.add_argument(
        "--refit",
        action="store_true",
        help="Regenerate the cached passive N=9 fit through the current core fitter.",
    )
    parser.add_argument("--weak-points", type=int, default=1001)
    parser.add_argument("--strong-points", type=int, default=5001)
    parser.add_argument("--time-points", type=int, default=2251)
    parser.add_argument("--no-plots", action="store_true")
    return parser


def main() -> None:
    args = _build_parser().parse_args()
    run_dir = run_comparison(
        output_dir=args.output_dir,
        response=args.response,
        refit=args.refit,
        weak_points=args.weak_points,
        strong_points=args.strong_points,
        time_points=args.time_points,
        make_plots=not args.no_plots,
    )
    print(f"Saved Sadeghi-2009 comparison to {run_dir}")


if __name__ == "__main__":
    main()
