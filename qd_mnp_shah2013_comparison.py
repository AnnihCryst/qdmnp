def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description=(
            "Build native symmetric-dimer counterparts of Shah et al. "
            "Phys. Rev. B 88, 075411 (2013), figures 1--4."
        )
    )
    parser.add_argument(
        "--article-pdf",
        type=Path,
        default=Path("articles/shah2013.pdf"),
    )
    parser.add_argument(
        "--output-dir",
        type=Path,
        default=Path("results/shah2013_native_dimer"),
    )
    parser.add_argument(
        "--decay-profile",
        choices=["naive", "purcell_cp"],
        default="purcell_cp",
    )
    parser.add_argument(
        "--response",
        choices=["modal", "material"],
        default="modal",
    )
    parser.add_argument(
        "--refit",
        action="store_true",
        help="Regenerate the cached N=10 response with HybridQDPlasmonModel.",
    )
    # 0.25 meV spacing resolves Gamma2/4 for both supported decay profiles.
    parser.add_argument("--energy-points", type=int, default=801)
    parser.add_argument("--intensity-points", type=int, default=81)
    parser.add_argument("--fluence-points", type=int, default=41)
    parser.add_argument("--quiet", action="store_true")
    return parser.parse_args()


def main() -> None:
    args = parse_args()
    metadata = run_comparison(
        profile=Shah2013Profile(),
        output_dir=args.output_dir,
        article_pdf=args.article_pdf,
        decay_profile=args.decay_profile,
        response=args.response,
        refit=args.refit,
        energy_points=args.energy_points,
        intensity_points=args.intensity_points,
        fluence_points=args.fluence_points,
        verbose=not args.quiet,
    )
    metrics = metadata["computed_metrics"]
    print(f"Wrote Shah native-dimer artifacts to {args.output_dir}")
    if metrics["linear_fano_local_min_found"]:
        fano_message = (
            "local Fano minimum "
            f"{metrics['linear_fano_min_energy_ev']:.6g} eV"
        )
    else:
        fano_message = "no local Fano minimum in the transition window"
    first_peak = metrics["first_resonant_fluence_peak_j_cm2"]
    if first_peak is None:
        fluence_message = "no resolved resonant fluence peak"
    else:
        fluence_message = f"first resonant fluence peak {first_peak:.6g} J/cm^2"
    print(
        f"Native result: {fano_message}; {fluence_message}."
    )
    print(
        "This is a native point-dipole comparison, not a DDA/CQED replication; "
        "inspect comparison_metadata.json before physical interpretation."
    )


if __name__ == "__main__":
    main()
