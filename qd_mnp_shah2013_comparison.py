def _plot_figure4(
    traces: dict[float, PulseEnvelopeTrace],
    path: Path,
) -> None:
    fluences = sorted(traces)
    fig, axes = plt.subplots(3, len(fluences), figsize=(12.2, 10.0), sharex=True)
    if len(fluences) == 1:
        axes = np.asarray(axes)[:, None]
    for column, fluence in enumerate(fluences):
        trace = traces[fluence]
        time_fs = np.asarray(au_to_fs(trace.t_au), dtype=float)
        mask = (time_fs >= -50.0) & (time_fs <= 150.0)
        uniform_time = np.linspace(-50.0, 150.0, 5001)
        carrier_phase = np.exp(
            -1j
            * trace.carrier_omega_au
            * np.asarray(fs_to_au(uniform_time), dtype=float)
        )

        def interpolate_complex(values: np.ndarray) -> np.ndarray:
            return np.interp(uniform_time, time_fs[mask], values[mask].real) + 1j * np.interp(
                uniform_time,
                time_fs[mask],
                values[mask].imag,
            )

        field_envelope = interpolate_complex(trace.field_envelope_au)
        qd_envelope = interpolate_complex(trace.qd_envelope_au)
        mnp_envelope = 2.0 * interpolate_complex(trace.each_mnp_envelope_au)
        field = np.real(field_envelope * carrier_phase)
        qd = np.real(qd_envelope * carrier_phase)
        mnp = np.real(mnp_envelope * carrier_phase)
        W = np.interp(uniform_time, time_fs[mask], trace.inversion[mask])
        population = 0.5 * (W + 1.0)
        field_si = np.asarray(field_au_to_si(field)) / 1e6
        qd_debye = qd * AU_DIPOLE_C_M / DEBYE_C_M
        mnp_kdebye = mnp * AU_DIPOLE_C_M / DEBYE_C_M / 1e3

        def visible_phase_lag(response: np.ndarray) -> np.ndarray:
            """Return a carrier-referenced phase only while it is observable."""

            amplitude = np.abs(response)
            cutoff = 0.02 * float(np.max(amplitude))
            lag = np.mod(
                np.angle(field_envelope) - np.angle(response),
                2.0 * np.pi,
            )
            return np.where(amplitude >= cutoff, lag, np.nan)

        axes[0, column].plot(uniform_time, field_si, color="0.25", lw=0.7)
        population_axis = axes[0, column].twinx()
        population_axis.plot(uniform_time, population, color="tab:red")
        population_axis.set_ylabel("QD population", color="tab:red")
        axes[0, column].set_ylabel("Field (MV/m)")
        axes[0, column].set_title(f"{fluence * 1e9:g} nJ/cm²")
        axes[1, column].plot(uniform_time, qd_debye, color="0.25", lw=0.7)
        qd_phase_axis = axes[1, column].twinx()
        qd_phase_axis.plot(
            uniform_time,
            visible_phase_lag(qd_envelope),
            color="tab:red",
        )
        qd_phase_axis.set_ylim(0.0, 2.0 * np.pi)
        qd_phase_axis.set_ylabel("QD phase lag", color="tab:red")
        axes[1, column].set_ylabel("QD dipole (D)")
        axes[2, column].plot(uniform_time, mnp_kdebye, color="0.25", lw=0.7)
        mnp_phase_axis = axes[2, column].twinx()
        mnp_phase_axis.plot(
            uniform_time,
            visible_phase_lag(mnp_envelope),
            color="tab:red",
        )
        mnp_phase_axis.set_ylim(0.0, 2.0 * np.pi)
        mnp_phase_axis.set_ylabel("dimer phase lag", color="tab:red")
        axes[2, column].set_ylabel("Dimer dipole (10³ D)")
        axes[2, column].set_xlabel("Time from pulse center (fs)")
        for row in range(3):
            axes[row, column].grid(alpha=0.2)
    fig.tight_layout()
    fig.savefig(path, dpi=180)
    plt.close(fig)


