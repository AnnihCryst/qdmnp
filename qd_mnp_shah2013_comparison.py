"""Native-model comparison with Shah et al., Phys. Rev. B 88, 075411 (2013).

The physical structure in the paper is an Au--CdSe--Au dimer, but the paper's
semiclassical equations replace the whole metal antenna by one fitted bright
plasmon oscillator.  This module answers a different and useful question:
what does the *current project model* predict for the two stated Au spheroids?

Each spheroid keeps the project's quasistatic Johnson--Christy ellipsoid
polarizability and its passive Lorentz-mode realization.  In the perfectly
symmetric longitudinal geometry used by Shah, the two induced dipoles are
equal.  The explicit two-particle problem therefore reduces exactly (within
the project's point-dipole approximation) to one set of modal coordinates:

    F = E + J*mu_QD + K*mu_MNP,
    mu_MNP = C*(alpha_inf*F + sum(q_k)),
    E_QD = l_QD*(E + 2*J*mu_MNP).

Here J couples the QD to either MNP and K couples the two MNPs.  The total
observable dipole is 2*mu_MNP + mu_QD.  No change is made to
``qd_mnp_rational_fit.py``; this file is a geometry adapter around its material,
unit, pulse, density-matrix and passive-modal APIs.

The corrected semiclassical rates printed in the paper are not a completely
positive two-level generator: Gamma2=1.265 meV is smaller than
gamma1_eff/2~=1.508 meV.  Production calculations therefore expose two honest
profiles only: ``naive`` (free-QD gamma1) and ``purcell_cp`` (the article's
Purcell population rate plus its thermal pure dephasing).  The latter is the
default and has Gamma2=gamma_thermal+gamma1_eff/2.
"""

