def _longitudinal_depolarization_factor(c_au: float, a_au: float) -> float:
    eccentricity_squared = float(1.0 - (a_au / c_au) ** 2)
    if eccentricity_squared <= 0.0:
        return 1.0 / 3.0
    eccentricity = float(np.sqrt(eccentricity_squared))
    return float(
        (1.0 - eccentricity_squared)
        * (np.arctanh(eccentricity) - eccentricity)
        / eccentricity**3
    )


def _alpha_model(
    energies_ev: float | np.ndarray,
    fit: RationalLorentzFit,
) -> np.ndarray:
    omega = np.asarray(eV_to_au(energies_ev), dtype=float)
    alpha = np.full_like(omega, fit.alpha_inf, dtype=complex)
    for strength, mode_omega, mode_gamma in zip(
        fit.strengths_au2,
        fit.omega_modes_au,
        fit.gamma_modes_au,
    ):
        alpha += strength / (
            mode_omega**2 - omega**2 - 1j * mode_gamma * omega
        )
    return alpha


def _single_particle_material_alpha_dimless(
    params: HybridSystemParams,
    energies_ev: float | np.ndarray,
) -> np.ndarray:
    depolarization = _longitudinal_depolarization_factor(
        params.c_au,
        params.a_au,
    )
    epsilon = params.material.epsilon_at(energies_ev)
    contrast = epsilon - params.eps_m
    return np.asarray(
        contrast / (params.eps_m + depolarization * contrast),
        dtype=complex,
    )


