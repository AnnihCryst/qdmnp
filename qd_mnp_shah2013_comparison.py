def build_shah_params(
    profile: Shah2013Profile,
    decay_profile: DecayProfile,
) -> HybridSystemParams:
    gamma_1_mev, gamma_2_mev = profile.rates_mev(decay_profile)
    return make_params_with_overrides(
        c_nm=profile.mnp_semimajor_nm,
        a_nm=profile.mnp_semiminor_nm,
        r_nm=profile.qd_to_mnp_center_nm,
        qd_radius_nm=profile.qd_radius_nm,
        eps_m=profile.eps_environment,
        eps_qd=profile.eps_qd_infinity,
        d_debye=profile.qd_dipole_debye,
        omega0_ev=profile.transition_energy_ev,
        gamma_population_mev=gamma_1_mev,
        gamma2_coherence_mev=gamma_2_mev,
        orientation="long",
        qd_dipole_convention="effective_external",
    )


class SymmetricDimerQDPlasmonModel:
    """Two identical native MNPs reduced to their symmetric bright sector."""

    fit_window_ev = (0.8, 3.0)

    def __init__(
        self,
        params: HybridSystemParams,
        fit: RationalLorentzFit,
        *,
        mnp_center_distance_nm: float,
        fit_provenance: str,
    ) -> None:
        self.params = params
        self.fit = fit
        self.n_modes = int(fit.strengths_au2.size)
        if params.G != 2.0:
            raise ValueError(
                "The Shah adapter is longitudinal and requires the fixed "
                "quasistatic factor G=2."
            )
        if params.axial_surface_gap_au <= 0.0:
            raise ValueError("The QD--MNP surface gap must be positive.")
        if params.Gamma_au < 0.5 * params.gamma_au:
            raise ValueError("Physical rates require Gamma2 >= gamma1/2.")
        self.C = float(params.eps_m * params.a_au**2 * params.c_au / 3.0)
        self.J = float(2.0 / (params.eps_m * params.R_au**3))
        self.mnp_center_distance_au = float(nm_to_au(mnp_center_distance_nm))
        if self.mnp_center_distance_au <= 2.0 * params.c_au:
            raise ValueError("The two MNP surfaces must have a positive gap.")
        if not np.isclose(
            self.mnp_center_distance_au,
            2.0 * params.R_au,
            rtol=1e-12,
            atol=0.0,
        ):
            raise ValueError(
                "Symmetric reduction requires the QD at the dimer center: "
                "D=2R."
            )
        self.K = float(
            2.0 / (params.eps_m * self.mnp_center_distance_au**3)
        )
        self.fit_provenance = fit_provenance
        instantaneous_denominator = 1.0 - self.K * self.C * fit.alpha_inf
        antisymmetric_denominator = 1.0 + self.K * self.C * fit.alpha_inf
        if min(abs(instantaneous_denominator), abs(antisymmetric_denominator)) < 1e-8:
            raise RuntimeError("The dimer instantaneous response is singular.")
        self._symmetric_instantaneous_denominator = float(
            instantaneous_denominator
        )
        self._antisymmetric_instantaneous_denominator = float(
            antisymmetric_denominator
        )
        self.stability = self._stability_audit()
        if not (
            self.stability.symmetric_stable
            and self.stability.antisymmetric_stable
        ):
            raise RuntimeError(
                "The native dimer has an unstable symmetric or antisymmetric "
                "field-free branch."
            )

    def alpha_single_dimless(
        self,
        energies_ev: float | np.ndarray,
        *,
        response: MNPResponse = "modal",
    ) -> np.ndarray:
        energies = np.asarray(energies_ev, dtype=float)
        if np.any(energies < self.fit_window_ev[0]) or np.any(
            energies > self.fit_window_ev[1]
        ):
            raise ValueError("Requested energy is outside the modal fit window.")
        if response == "modal":
            return _alpha_model(energies, self.fit)
        if response == "material":
            return _single_particle_material_alpha_dimless(self.params, energies)
        raise ValueError("response must be 'modal' or 'material'.")

    def alpha_each_mnp_au(
        self,
        energies_ev: float | np.ndarray,
        *,
        response: MNPResponse = "modal",
    ) -> np.ndarray:
        """Each-particle response after mutual MNP--MNP dressing."""

        alpha_single = self.C * self.alpha_single_dimless(
            energies_ev,
            response=response,
        )
        return alpha_single / (1.0 - self.K * alpha_single)

    def alpha_bare_dimer_au(
        self,
        energies_ev: float | np.ndarray,
        *,
        response: MNPResponse = "modal",
    ) -> np.ndarray:
        return 2.0 * self.alpha_each_mnp_au(
            energies_ev,
            response=response,
        )

    def linear_coupled_alpha_au(
        self,
        energies_ev: float | np.ndarray,
        *,
        response: MNPResponse = "modal",
    ) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
        energies = np.asarray(energies_ev, dtype=float)
        omega = np.asarray(eV_to_au(energies), dtype=float)
        alpha_dimer = self.alpha_bare_dimer_au(energies, response=response)
        beta_qd = qd_linear_polarizability_au(
            omega,
            self.params.d_au,
            self.params.omega0_au,
            self.params.Gamma_au,
            self.params.qd_local_field_factor,
        )
        denominator = 1.0 - self.J**2 * alpha_dimer * beta_qd
        mu_dimer_over_e = (
            alpha_dimer * (1.0 + self.J * beta_qd) / denominator
        )
        mu_qd_over_e = beta_qd * (1.0 + self.J * alpha_dimer) / denominator
        return (
            (mu_dimer_over_e + mu_qd_over_e) / self.params.eps_m,
            alpha_dimer / self.params.eps_m,
            beta_qd / self.params.eps_m,
        )

    def initial_state(self) -> np.ndarray:
        state = np.zeros(2 * self.n_modes + 3, dtype=float)
        state[2 * self.n_modes] = -1.0
        return state

    def rhs(self, t_au: float, state: np.ndarray, pulse: GaussianPulse) -> np.ndarray:
        p = self.params
        q = state[: 2 * self.n_modes : 2]
        velocity = state[1 : 2 * self.n_modes : 2]
        W, Q, P = state[2 * self.n_modes : 2 * self.n_modes + 3]
        incident = float(pulse.field(t_au))
        local_field = p.qd_local_field_factor
        mu_qd = local_field * p.d_au * P
        drive = (
            incident
            + self.J * mu_qd
            + self.K * self.C * float(np.sum(q))
        ) / self._symmetric_instantaneous_denominator
        mu_each = self.C * (self.fit.alpha_inf * drive + float(np.sum(q)))
        qd_field = local_field * (incident + 2.0 * self.J * mu_each)
        rabi = 2.0 * p.d_au * qd_field

        derivative = np.zeros_like(state)
        for index, (coordinate, speed, strength, omega, gamma) in enumerate(
            zip(
                q,
                velocity,
                self.fit.strengths_au2,
                self.fit.omega_modes_au,
                self.fit.gamma_modes_au,
            )
        ):
            derivative[2 * index] = speed
            derivative[2 * index + 1] = (
                strength * drive - gamma * speed - omega**2 * coordinate
            )
        derivative[2 * self.n_modes] = rabi * Q - p.gamma_au * (W + 1.0)
        derivative[2 * self.n_modes + 1] = (
            -p.omega0_au * P - rabi * W - p.Gamma_au * Q
        )
        derivative[2 * self.n_modes + 2] = p.omega0_au * Q - p.Gamma_au * P
        return derivative

    def reconstruct(
        self,
        t_au: np.ndarray,
        state: np.ndarray,
        pulse: GaussianPulse,
    ) -> tuple[np.ndarray, np.ndarray, np.ndarray, np.ndarray]:
        p = self.params
        q = state[: 2 * self.n_modes : 2]
        P = state[2 * self.n_modes + 2]
        incident = pulse.field(t_au)
        mu_qd = p.qd_local_field_factor * p.d_au * P
        drive = (
            incident + self.J * mu_qd + self.K * self.C * np.sum(q, axis=0)
        ) / self._symmetric_instantaneous_denominator
        mu_each = self.C * (self.fit.alpha_inf * drive + np.sum(q, axis=0))
        total = 2.0 * mu_each + mu_qd
        return incident, mu_each, mu_qd, total

    def _numerical_jacobian(self) -> np.ndarray:
        ground = self.initial_state()
        zero_pulse = GaussianPulse(
            E0_au=1e-30,
            omegaL_au=self.params.omega0_au,
            tau_au=float(fs_to_au(20.0)),
            tau_kind="fwhm_intensity",
        )
        size = ground.size
        jacobian = np.empty((size, size), dtype=float)
        for column in range(size):
            step = 1e-7 * max(1.0, abs(float(ground[column])))
            plus = ground.copy()
            minus = ground.copy()
            plus[column] += step
            minus[column] -= step
            jacobian[:, column] = (
                self.rhs(0.0, plus, zero_pulse)
                - self.rhs(0.0, minus, zero_pulse)
            ) / (2.0 * step)
        return jacobian

    def _antisymmetric_jacobian(self) -> np.ndarray:
        size = 2 * self.n_modes
        jacobian = np.zeros((size, size), dtype=float)
        drive_coeff = -self.K * self.C / self._antisymmetric_instantaneous_denominator
        for index, (strength, omega, gamma) in enumerate(
            zip(
                self.fit.strengths_au2,
                self.fit.omega_modes_au,
                self.fit.gamma_modes_au,
            )
        ):
            q_index = 2 * index
            v_index = q_index + 1
            jacobian[q_index, v_index] = 1.0
            jacobian[v_index, v_index] = -gamma
            jacobian[v_index, q_index] = -omega**2
            jacobian[v_index, 0 : 2 * self.n_modes : 2] += (
                strength * drive_coeff
            )
        return jacobian

    def _stability_audit(self) -> StabilityAudit:
        symmetric_poles = np.linalg.eigvals(self._numerical_jacobian())
        antisymmetric_poles = np.linalg.eigvals(self._antisymmetric_jacobian())
        scale = max(
            self.params.omega0_au,
            float(np.max(self.fit.omega_modes_au)),
            1e-15,
        )
        tolerance = 1e-10 * scale
        symmetric_poles = np.asarray(symmetric_poles, dtype=complex)
        antisymmetric_poles = np.asarray(antisymmetric_poles, dtype=complex)
        symmetric_poles.setflags(write=False)
        antisymmetric_poles.setflags(write=False)
        return StabilityAudit(
            symmetric_poles_au=symmetric_poles,
            antisymmetric_poles_au=antisymmetric_poles,
            symmetric_stable=bool(np.max(symmetric_poles.real) <= tolerance),
            antisymmetric_stable=bool(
                np.max(antisymmetric_poles.real) <= tolerance
            ),
            tolerance_au=float(tolerance),
        )

    def coherent_decay_rate_au(self) -> float:
        jacobian = self._numerical_jacobian()
        W_index = 2 * self.n_modes
        coherent = np.delete(np.delete(jacobian, W_index, axis=0), W_index, axis=1)
        symmetric_rate = -float(np.max(np.linalg.eigvals(coherent).real))
        antisymmetric_rate = -float(
            np.max(self.stability.antisymmetric_poles_au.real)
        )
        rate = min(symmetric_rate, antisymmetric_rate)
        if not np.isfinite(rate) or rate <= 0.0:
            raise RuntimeError("No decaying coherent dimer branch was found.")
        return float(rate)


def build_native_dimer_model(
    profile: Shah2013Profile,
    *,
    decay_profile: DecayProfile = "purcell_cp",
    refit: bool = False,
    verbose: bool = False,
) -> SymmetricDimerQDPlasmonModel:
    params = build_shah_params(profile, decay_profile)
    if refit:
        native_single = HybridQDPlasmonModel(
            params,
            orientation="long",
            n_modes=10,
            fit_window_eV=(0.8, 3.0),
            max_fit_pointwise_relative_error=0.051,
            verbose=verbose,
        )
        fit = native_single.fit
        provenance = "refitted by HybridQDPlasmonModel"
    else:
        fit = _cached_shah_fit(params)
        provenance = "cached output of HybridQDPlasmonModel N=10 fit"
    return SymmetricDimerQDPlasmonModel(
        params,
        fit,
        mnp_center_distance_nm=profile.mnp_center_distance_nm,
        fit_provenance=provenance,
    )


def peak_field_from_intensity_au(
    intensity_w_cm2: float,
    eps_m: float,
) -> float:
    if not np.isfinite(intensity_w_cm2) or intensity_w_cm2 <= 0.0:
        raise ValueError("Intensity must be finite and positive.")
    field_si = np.sqrt(
        2.0 * intensity_w_cm2 * 1e4
        / (np.sqrt(eps_m) * epsilon_0 * C_SI)
    )
    return float(field_si_to_au(field_si))


def pulse_from_fluence(
    profile: Shah2013Profile,
    fluence_j_cm2: float,
) -> GaussianPulse:
    if not np.isfinite(fluence_j_cm2) or fluence_j_cm2 <= 0.0:
        raise ValueError("Fluence must be finite and positive.")
    tau_au = float(fs_to_au(profile.pulse_fwhm_intensity_fs))
    sigma_au = tau_au / (2.0 * np.sqrt(np.log(2.0)))
    sigma_s = sigma_au * AU_TIME_S
    omega_au = float(eV_to_au(profile.transition_energy_ev))
    overlap = np.exp(-(omega_au * sigma_au) ** 2)
    fluence_j_m2 = fluence_j_cm2 * 1e4
    denominator = (
        np.sqrt(profile.eps_environment)
        * epsilon_0
        * C_SI
        * 0.5
        * np.sqrt(np.pi)
        * sigma_s
        * (1.0 + overlap)
    )
    field_si = np.sqrt(fluence_j_m2 / denominator)
    pulse = GaussianPulse(
        E0_au=float(field_si_to_au(field_si)),
        omegaL_au=omega_au,
        tau_au=tau_au,
        tau_kind="fwhm_intensity",
    )
    reconstructed = pulse.fluence_j_cm2(eps_m=profile.eps_environment)
    if not np.isclose(reconstructed, fluence_j_cm2, rtol=2e-13, atol=0.0):
        raise RuntimeError("Internal pulse-fluence normalization mismatch.")
    return pulse


def _harmonic_state_for_inversion(
    model: SymmetricDimerQDPlasmonModel,
    *,
    energy_ev: float,
    field_amplitude_au: float,
    inversion: float,
    response: MNPResponse,
    alpha_dimer_au: complex | None = None,
    bloch_factor_au: complex | None = None,
) -> tuple[float, complex, complex, complex, complex, complex]:
    p = model.params
    omega = float(eV_to_au(energy_ev))
    alpha_dimer = (
        complex(model.alpha_bare_dimer_au(energy_ev, response=response))
        if alpha_dimer_au is None
        else complex(alpha_dimer_au)
    )
    bloch_factor = (
        p.omega0_au
        / (p.omega0_au**2 + (p.Gamma_au - 1j * omega) ** 2)
        if bloch_factor_au is None
        else complex(bloch_factor_au)
    )
    local = p.qd_local_field_factor
    denominator = (
        1.0
        + 2.0
        * p.d_au**2
        * local**2
        * inversion
        * bloch_factor
        * model.J**2
        * alpha_dimer
    )
    P_amplitude = (
        -2.0
        * p.d_au
        * local
        * inversion
        * bloch_factor
        * (1.0 + model.J * alpha_dimer)
        * field_amplitude_au
        / denominator
    )
    mu_qd = local * p.d_au * P_amplitude
    mu_dimer = alpha_dimer * (field_amplitude_au + model.J * mu_qd)
    local_field = local * (field_amplitude_au + model.J * mu_dimer)
    rabi_amplitude = 2.0 * p.d_au * local_field
    Q_amplitude = (p.Gamma_au - 1j * omega) * P_amplitude / p.omega0_au
    population_residual = (
        0.5 * np.real(rabi_amplitude * np.conj(Q_amplitude))
        - p.gamma_au * (inversion + 1.0)
    )
    total_dipole = mu_dimer + mu_qd
    return (
        float(population_residual),
        P_amplitude,
        Q_amplitude,
        mu_qd,
        0.5 * mu_dimer,
        total_dipole,
    )


def solve_cw_harmonic_state(
    model: SymmetricDimerQDPlasmonModel,
    *,
    energy_ev: float,
    intensity_w_cm2: float,
    response: MNPResponse = "modal",
    preferred_inversion: float | None = None,
) -> HarmonicState:
    field_amplitude = peak_field_from_intensity_au(
        intensity_w_cm2,
        model.params.eps_m,
    )
    p = model.params
    omega = float(eV_to_au(energy_ev))
    alpha_dimer = complex(model.alpha_bare_dimer_au(energy_ev, response=response))
    bloch_factor = p.omega0_au / (
        p.omega0_au**2 + (p.Gamma_au - 1j * omega) ** 2
    )

    def residual(inversion: float) -> float:
        return _harmonic_state_for_inversion(
            model,
            energy_ev=energy_ev,
            field_amplitude_au=field_amplitude,
            inversion=inversion,
            response=response,
            alpha_dimer_au=alpha_dimer,
            bloch_factor_au=bloch_factor,
        )[0]

    inversion_grid = np.linspace(-1.0, 0.0, 401)
    local = p.qd_local_field_factor
    denominator = (
        1.0
        + 2.0
        * p.d_au**2
        * local**2
        * inversion_grid
        * bloch_factor
        * model.J**2
        * alpha_dimer
    )
    P_grid = (
        -2.0
        * p.d_au
        * local
        * inversion_grid
        * bloch_factor
        * (1.0 + model.J * alpha_dimer)
        * field_amplitude
        / denominator
    )
    mu_qd_grid = local * p.d_au * P_grid
    mu_dimer_grid = alpha_dimer * (field_amplitude + model.J * mu_qd_grid)
    local_field_grid = local * (field_amplitude + model.J * mu_dimer_grid)
    rabi_grid = 2.0 * p.d_au * local_field_grid
    Q_grid = (p.Gamma_au - 1j * omega) * P_grid / p.omega0_au
    residuals = (
        0.5 * np.real(rabi_grid * np.conj(Q_grid))
        - p.gamma_au * (inversion_grid + 1.0)
    )
    roots: list[float] = []
    for left, right, f_left, f_right in zip(
        inversion_grid[:-1],
        inversion_grid[1:],
        residuals[:-1],
        residuals[1:],
    ):
        if f_left == 0.0:
            roots.append(float(left))
        if f_left * f_right < 0.0:
            roots.append(float(brentq(residual, left, right, xtol=1e-13)))
    if residuals[-1] == 0.0:
        roots.append(0.0)
    roots = sorted(set(round(value, 13) for value in roots))
    if not roots:
        raise RuntimeError("No physical CW inversion root in [-1, 0].")
    target = -1.0 if preferred_inversion is None else preferred_inversion
    inversion = min(roots, key=lambda value: abs(value - target))
    _, P, Q, mu_qd, mu_each, total = _harmonic_state_for_inversion(
        model,
        energy_ev=energy_ev,
        field_amplitude_au=field_amplitude,
        inversion=inversion,
        response=response,
        alpha_dimer_au=alpha_dimer,
        bloch_factor_au=bloch_factor,
    )
    effective_alpha = total / (model.params.eps_m * field_amplitude)
    work_loss = float(
        quasistatic_work_loss_cross_section_cm2(
            np.asarray([effective_alpha]),
            np.asarray([eV_to_au(energy_ev)]),
            model.params.eps_m,
        )[0]
    )
    # The RWA density matrix retains the co-rotating optical coherence only.
    # With the present Bloch convention Q=-i*P on the positive-frequency
    # branch, so (P+iQ)/2 is its physical transverse Bloch amplitude.
    transverse = 0.5 * (P + 1j * Q)
    max_radius = float(np.sqrt(inversion**2 + np.abs(transverse) ** 2))
    if max_radius > 1.0 + 5e-5:
        raise RuntimeError(
            "The RWA steady state left the Bloch ball: "
            f"radius={max_radius:.9g}."
        )
    return HarmonicState(
        energy_ev=float(energy_ev),
        intensity_w_cm2=float(intensity_w_cm2),
        inversion=float(inversion),
        excited_population=float(0.5 * (inversion + 1.0)),
        qd_bloch_p_amplitude=P,
        qd_bloch_q_amplitude=Q,
        qd_dipole_au=mu_qd,
        each_mnp_dipole_au=mu_each,
        total_dipole_au=total,
        effective_alpha_au=effective_alpha,
        paper_work_loss_cm2=work_loss,
        root_count=len(roots),
        max_periodic_bloch_radius=max_radius,
    )


def scan_cw_spectrum(
    model: SymmetricDimerQDPlasmonModel,
    energies_ev: np.ndarray,
    intensity_w_cm2: float,
    *,
    response: MNPResponse = "modal",
) -> list[HarmonicState]:
    states: list[HarmonicState] = []
    previous = None
    for energy in np.asarray(energies_ev, dtype=float):
        state = solve_cw_harmonic_state(
            model,
            energy_ev=float(energy),
            intensity_w_cm2=intensity_w_cm2,
            response=response,
            preferred_inversion=previous,
        )
        states.append(state)
        previous = state.inversion
    return states


def _tail_ratio(total_dipole: np.ndarray) -> float:
    count = max(8, total_dipole.size // 100)
    scale = max(float(np.max(np.abs(total_dipole))), np.finfo(float).tiny)
    return float(np.max(np.abs(total_dipole[-count:])) / scale)


def solve_pulse_trace(
    model: SymmetricDimerQDPlasmonModel,
    profile: Shah2013Profile,
    fluence_j_cm2: float,
    *,
    rtol: float = 2e-8,
    atol: float = 2e-10,
    samples_per_fastest_cycle: int = 24,
    tail_decay_times: float = 8.0,
) -> PulseTrace:
    pulse = pulse_from_fluence(profile, fluence_j_cm2)
    spectral_fraction = pulse.positive_frequency_spectral_fraction(
        model.fit_window_ev
    )
    if spectral_fraction < 0.999:
        raise ValueError(
            "The 20 fs pulse is not covered by the modal fit window: "
            f"fraction={spectral_fraction:.9g}."
        )
    fastest = max(
        pulse.omegaL_au,
        model.params.omega0_au,
        float(np.max(model.fit.omega_modes_au)),
        float(np.max(np.abs(model.stability.symmetric_poles_au))),
        float(np.max(np.abs(model.stability.antisymmetric_poles_au))),
    )
    max_step = float(2.0 * np.pi / (samples_per_fastest_cycle * fastest))
    t_start = float(-8.0 * pulse.sigma_t_au)
    coherent_rate = model.coherent_decay_rate_au()
    t_end = float(
        max(8.0 * pulse.sigma_t_au, tail_decay_times / coherent_rate)
    )
    solution = solve_ivp(
        lambda t, y: model.rhs(t, y, pulse),
        (t_start, t_end),
        model.initial_state(),
        method="DOP853",
        rtol=rtol,
        atol=atol,
        max_step=max_step,
        dense_output=False,
    )
    if not solution.success:
        raise RuntimeError(solution.message)
    field, mu_each, mu_qd, total = model.reconstruct(
        solution.t,
        solution.y,
        pulse,
    )
    W, Q, P = solution.y[2 * model.n_modes : 2 * model.n_modes + 3]
    radius = np.sqrt(W**2 + Q**2 + P**2)
    max_radius = float(np.max(radius))
    min_eigenvalue = float(np.min(0.5 * (1.0 - radius)))
    if min_eigenvalue < -1e-6:
        raise RuntimeError(
            "Pulse trajectory violates density-matrix positivity: "
            f"min eigenvalue={min_eigenvalue:.9g}."
        )
    tail = _tail_ratio(total)
    if tail > 5e-4:
        raise RuntimeError(
            "Post-pulse coherent tail is not converged: "
            f"tail ratio={tail:.6g}."
        )
    return PulseTrace(
        fluence_j_cm2=float(fluence_j_cm2),
        t_au=np.asarray(solution.t),
        y=np.asarray(solution.y),
        field_au=np.asarray(field),
        each_mnp_dipole_au=np.asarray(mu_each),
        qd_dipole_au=np.asarray(mu_qd),
        total_dipole_au=np.asarray(total),
        max_bloch_radius=max_radius,
        min_density_eigenvalue=min_eigenvalue,
        tail_ratio=tail,
        solver_nfev=int(solution.nfev),
        max_step_au=max_step,
    )


def pulse_spectral_alpha_au(
    trace: PulseTrace,
    profile: Shah2013Profile,
    energies_ev: np.ndarray,
) -> np.ndarray:
    energies = np.asarray(energies_ev, dtype=float)
    omega = np.asarray(eV_to_au(energies), dtype=float)
    numerator = np.empty(energies.shape, dtype=complex)
    denominator = np.empty(energies.shape, dtype=complex)
    for start in range(0, energies.size, 32):
        stop = min(start + 32, energies.size)
        # The native harmonic response uses exp(-i*omega*t), so recovering its
        # positive-frequency amplitude from a real trace requires exp(+i*omega*t).
        # This is also the sign for which a passive alpha has Im(alpha)>=0.
        phase = np.exp(1j * omega[start:stop, None] * trace.t_au[None, :])
        numerator[start:stop] = np.trapezoid(
            phase * trace.total_dipole_au[None, :],
            trace.t_au,
            axis=1,
        )
        denominator[start:stop] = np.trapezoid(
            phase * trace.field_au[None, :],
            trace.t_au,
            axis=1,
        )
    denominator_scale = max(float(np.max(np.abs(denominator))), np.finfo(float).tiny)
    reliable = np.abs(denominator) >= 1e-8 * denominator_scale
    result = np.full(energies.shape, np.nan + 1j * np.nan, dtype=complex)
    result[reliable] = numerator[reliable] / (
        profile.eps_environment * denominator[reliable]
    )
    return result


def _unpack_envelope_state(
    state: np.ndarray,
    n_modes: int,
) -> tuple[np.ndarray, np.ndarray, np.ndarray, np.ndarray]:
    modal = state[: 2 * n_modes : 2] + 1j * state[1 : 2 * n_modes : 2]
    offset = 2 * n_modes
    # Strict optical RWA: keep only R=(P+iQ)/2.  On this co-rotating branch
    # P=R and Q=-iR; the discarded orthogonal combination oscillates near
    # 2*omega_L in the rotating frame.
    P = state[offset] + 1j * state[offset + 1]
    Q = -1j * P
    W = state[offset + 2]
    return modal, P, Q, W


def _pack_complex_derivative(
    modal: np.ndarray,
    coherence: complex,
    W: float,
) -> np.ndarray:
    derivative = np.empty(2 * modal.size + 3, dtype=float)
    derivative[: 2 * modal.size : 2] = modal.real
    derivative[1 : 2 * modal.size : 2] = modal.imag
    offset = 2 * modal.size
    derivative[offset : offset + 3] = [
        coherence.real,
        coherence.imag,
        W,
    ]
    return derivative


def _rwa_periodic_bloch_radius(
    inversion: np.ndarray,
    P: np.ndarray,
    Q: np.ndarray,
) -> np.ndarray:
    """Bloch radius of the retained co-rotating optical coherence.

    For a positive-frequency Bloch solution the harmonic amplitudes obey
    Q=-i*P.  The physical transverse amplitude is therefore
    (P+i*Q)/2.  The orthogonal combination is the counter-rotating component
    discarded by RWA and must not be counted as a second coherence.
    """

    transverse = 0.5 * (P + 1j * Q)
    return np.sqrt(np.maximum(0.0, inversion**2 + np.abs(transverse) ** 2))


def solve_pulse_envelope_trace(
    model: SymmetricDimerQDPlasmonModel,
    profile: Shah2013Profile,
    fluence_j_cm2: float,
    *,
    rtol: float = 2e-8,
    atol: float = 2e-10,
    tail_decay_times: float = 8.0,
) -> PulseEnvelopeTrace:
    """Integrate the native modal/Bloch equations in a rotating frame.

    The second-order modal equations are reduced to their positive-frequency
    slowly varying amplitudes.  At steady state this realization gives exactly
    the same Lorentz denominator at the carrier.  Across the 20-fs bandwidth it
    is the usual first-order RWA used and explicitly checked by Shah et al.
    """

    pulse = pulse_from_fluence(profile, fluence_j_cm2)
    spectral_fraction = pulse.positive_frequency_spectral_fraction(
        model.fit_window_ev
    )
    if spectral_fraction < 0.999:
        raise ValueError(
            "The 20 fs pulse is not covered by the modal fit window: "
            f"fraction={spectral_fraction:.9g}."
        )
    omega_l = pulse.omegaL_au
    sigma = pulse.sigma_t_au
    p = model.params

    initial = np.zeros(2 * model.n_modes + 3, dtype=float)
    initial[-1] = -1.0

    def rhs(t_au: float, state: np.ndarray) -> np.ndarray:
        modal, P, Q, W = _unpack_envelope_state(state, model.n_modes)
        field_envelope = pulse.E0_au * np.exp(-0.5 * (t_au / sigma) ** 2)
        mu_qd = p.qd_local_field_factor * p.d_au * P
        drive = (
            field_envelope
            + model.J * mu_qd
            + model.K * model.C * np.sum(modal)
        ) / model._symmetric_instantaneous_denominator
        mu_each = model.C * (model.fit.alpha_inf * drive + np.sum(modal))
        qd_field = p.qd_local_field_factor * (
            field_envelope + 2.0 * model.J * mu_each
        )
        rabi = 2.0 * p.d_au * qd_field
        modal_denominator = (
            model.fit.omega_modes_au**2
            - omega_l**2
            - 1j * model.fit.gamma_modes_au * omega_l
        )
        modal_derivative = (
            model.fit.strengths_au2 * drive - modal_denominator * modal
        ) / (model.fit.gamma_modes_au - 2j * omega_l)
        coherence_derivative = (
            (1j * (omega_l - p.omega0_au) - p.Gamma_au) * P
            - 0.5j * rabi * W
        )
        W_derivative = (
            0.5 * np.real(rabi * np.conj(Q)) - p.gamma_au * (W + 1.0)
        )
        return _pack_complex_derivative(
            modal_derivative,
            coherence_derivative,
            float(W_derivative),
        )

    t_start = float(-8.0 * sigma)
    t_end = float(max(8.0 * sigma, tail_decay_times / model.coherent_decay_rate_au()))
    solution = solve_ivp(
        rhs,
        (t_start, t_end),
        initial,
        method="Radau",
        rtol=rtol,
        atol=atol,
        dense_output=False,
    )
    if not solution.success:
        raise RuntimeError(solution.message)
    modal, P, Q, W = _unpack_envelope_state(solution.y, model.n_modes)
    field_envelope = pulse.E0_au * np.exp(-0.5 * (solution.t / sigma) ** 2)
    mu_qd = p.qd_local_field_factor * p.d_au * P
    drive = (
        field_envelope
        + model.J * mu_qd
        + model.K * model.C * np.sum(modal, axis=0)
    ) / model._symmetric_instantaneous_denominator
    mu_each = model.C * (model.fit.alpha_inf * drive + np.sum(modal, axis=0))
    total = 2.0 * mu_each + mu_qd
    radius = _rwa_periodic_bloch_radius(W, P, Q)
    max_radius = float(np.max(radius))
    min_eigenvalue = float(np.min(0.5 * (1.0 - radius)))
    if min_eigenvalue < -1e-6:
        raise RuntimeError(
            "RWA pulse trajectory violates density-matrix positivity: "
            f"min eigenvalue={min_eigenvalue:.9g}."
        )
    tail = _tail_ratio(total)
    if tail > 5e-4:
        raise RuntimeError(
            "RWA post-pulse coherent tail is not converged: "
            f"tail ratio={tail:.6g}."
        )
    return PulseEnvelopeTrace(
        fluence_j_cm2=float(fluence_j_cm2),
        carrier_omega_au=float(omega_l),
        t_au=np.asarray(solution.t),
        state=np.asarray(solution.y),
        field_envelope_au=np.asarray(field_envelope, dtype=complex),
        each_mnp_envelope_au=np.asarray(mu_each, dtype=complex),
        qd_envelope_au=np.asarray(mu_qd, dtype=complex),
        total_envelope_au=np.asarray(total, dtype=complex),
        inversion=np.asarray(W, dtype=float),
        max_bloch_radius=max_radius,
        min_density_eigenvalue=min_eigenvalue,
        tail_ratio=tail,
        solver_nfev=int(solution.nfev),
    )


def pulse_envelope_spectral_alpha_au(
    trace: PulseEnvelopeTrace,
    profile: Shah2013Profile,
    energies_ev: np.ndarray,
) -> np.ndarray:
    energies = np.asarray(energies_ev, dtype=float)
    detuning = np.asarray(eV_to_au(energies), dtype=float) - trace.carrier_omega_au
    numerator = np.empty(energies.shape, dtype=complex)
    denominator = np.empty(energies.shape, dtype=complex)
    for start in range(0, energies.size, 32):
        stop = min(start + 32, energies.size)
        phase = np.exp(1j * detuning[start:stop, None] * trace.t_au[None, :])
        numerator[start:stop] = np.trapezoid(
            phase * trace.total_envelope_au[None, :],
            trace.t_au,
            axis=1,
        )
        denominator[start:stop] = np.trapezoid(
            phase * trace.field_envelope_au[None, :],
            trace.t_au,
            axis=1,
        )
    scale = max(float(np.max(np.abs(denominator))), np.finfo(float).tiny)
    reliable = np.abs(denominator) >= 1e-8 * scale
    alpha = np.full(energies.shape, np.nan + 1j * np.nan, dtype=complex)
    alpha[reliable] = numerator[reliable] / (
        profile.eps_environment * denominator[reliable]
    )
    return alpha


def pulse_envelope_work_loss_spectrum_cm2(
    trace: PulseEnvelopeTrace,
    profile: Shah2013Profile,
    energies_ev: np.ndarray,
) -> np.ndarray:
    alpha = pulse_envelope_spectral_alpha_au(trace, profile, energies_ev)
    return np.asarray(
        quasistatic_work_loss_cross_section_cm2(
            alpha,
            np.asarray(eV_to_au(energies_ev), dtype=float),
            profile.eps_environment,
        ),
        dtype=float,
    )


def pulse_work_loss_spectrum_cm2(
    trace: PulseTrace,
    profile: Shah2013Profile,
    energies_ev: np.ndarray,
) -> np.ndarray:
    alpha = pulse_spectral_alpha_au(trace, profile, energies_ev)
    values = quasistatic_work_loss_cross_section_cm2(
        alpha,
        np.asarray(eV_to_au(energies_ev), dtype=float),
        profile.eps_environment,
    )
    return np.asarray(values, dtype=float)


def _write_csv(path: Path, rows: Iterable[dict]) -> None:
    rows = list(rows)
    if not rows:
        raise ValueError(f"Cannot write empty CSV: {path}")
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=list(rows[0].keys()))
        writer.writeheader()
        writer.writerows(rows)


def _article_pdf_hash(path: Path) -> str | None:
    if not path.exists():
        return None
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for block in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def _nearest_local_extremum_index(
    energies_ev: np.ndarray,
    values: np.ndarray,
    *,
    center_ev: float,
    kind: Literal["minimum", "maximum"],
    half_window_ev: float = 0.03,
) -> int | None:
    """Locate a genuine local Fano extremum near the QD transition.

    A global minimum over the full plotting window is usually just the low-
    energy edge of the broad plasmon band and must not be labelled as the
    narrow Fano minimum.
    """

    energies = np.asarray(energies_ev, dtype=float)
    observable = np.asarray(values, dtype=float)
    sign = -1.0 if kind == "minimum" else 1.0
    candidates, _ = find_peaks(sign * observable)
    candidates = candidates[
        np.abs(energies[candidates] - center_ev) <= half_window_ev
    ]
    if candidates.size == 0:
        return None
    return int(
        candidates[
            np.argmin(np.abs(energies[candidates] - center_ev))
        ]
    )


