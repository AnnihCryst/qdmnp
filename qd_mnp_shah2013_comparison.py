@dataclass(frozen=True)
class Shah2013Profile:
    """Parameters explicitly stated in the paper and its Supplement."""

    mnp_semimajor_nm: float = 15.0
    mnp_semiminor_nm: float = 10.0
    mnp_surface_gap_nm: float = 6.0
    qd_radius_nm: float = 2.0
    eps_environment: float = 2.25
    eps_qd_infinity: float = 5.8
    transition_energy_ev: float = 2.042
    qd_dipole_debye: float = 13.91
    effective_dimer_dipole_debye: float = 2994.0
    plasmon_linewidth_mev: float = 150.2
    coupling_g_mev: float = 10.841
    qd_thermal_dephasing_mev: float = 1.265
    qd_free_population_decay_mev: float = 0.000268
    pulse_fwhm_intensity_fs: float = 20.0
    cw_intensities_w_cm2: tuple[float, ...] = (
        1.0e3,
        1.0e4,
        1.0e5,
        1.0e6,
    )
    pulse_fluences_j_cm2: tuple[float, ...] = (
        5.0e-9,
        5.0e-8,
        5.0e-7,
        5.0e-6,
    )

    def __post_init__(self) -> None:
        values = np.asarray(
            [
                self.mnp_semimajor_nm,
                self.mnp_semiminor_nm,
                self.mnp_surface_gap_nm,
                self.qd_radius_nm,
                self.eps_environment,
                self.eps_qd_infinity,
                self.transition_energy_ev,
                self.qd_dipole_debye,
                self.effective_dimer_dipole_debye,
                self.plasmon_linewidth_mev,
                self.coupling_g_mev,
                self.qd_thermal_dephasing_mev,
                self.qd_free_population_decay_mev,
                self.pulse_fwhm_intensity_fs,
            ],
            dtype=float,
        )
        if np.any(~np.isfinite(values)) or np.any(values <= 0.0):
            raise ValueError("All Shah profile constants must be finite and positive.")
        if self.mnp_semimajor_nm < self.mnp_semiminor_nm:
            raise ValueError("The Shah Au particles are prolate: semimajor >= semiminor.")
        if self.qd_mnp_surface_gap_nm <= 0.0:
            raise ValueError(
                "The centered QD must have a strictly positive surface gap "
                "to both MNPs."
            )
        if any(value <= 0.0 for value in self.cw_intensities_w_cm2):
            raise ValueError("CW intensities must be positive.")
        if any(value <= 0.0 for value in self.pulse_fluences_j_cm2):
            raise ValueError("Pulse fluences must be positive.")

    @property
    def mnp_center_distance_nm(self) -> float:
        return 2.0 * self.mnp_semimajor_nm + self.mnp_surface_gap_nm

    @property
    def qd_to_mnp_center_nm(self) -> float:
        return 0.5 * self.mnp_center_distance_nm

    @property
    def qd_mnp_surface_gap_nm(self) -> float:
        return (
            self.qd_to_mnp_center_nm
            - self.mnp_semimajor_nm
            - self.qd_radius_nm
        )

    @property
    def effective_population_decay_mev(self) -> float:
        g = self.coupling_g_mev
        gamma_s = self.plasmon_linewidth_mev
        gamma_1 = self.qd_free_population_decay_mev
        gamma_2 = self.qd_thermal_dephasing_mev
        return float(
            gamma_1
            + 4.0 * g**2
            / (4.0 * g**2 / gamma_s + gamma_1 + 2.0 * gamma_2 + gamma_s)
        )

    def rates_mev(self, decay_profile: DecayProfile) -> tuple[float, float]:
        """Return population gamma1 and total coherence Gamma2."""

        if decay_profile == "naive":
            gamma_1 = self.qd_free_population_decay_mev
            gamma_2_total = self.qd_thermal_dephasing_mev + 0.5 * gamma_1
        elif decay_profile == "purcell_cp":
            gamma_1 = self.effective_population_decay_mev
            gamma_2_total = self.qd_thermal_dephasing_mev + 0.5 * gamma_1
        else:
            raise ValueError("decay_profile must be 'naive' or 'purcell_cp'.")
        return float(gamma_1), float(gamma_2_total)


